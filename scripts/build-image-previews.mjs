import fs from 'node:fs/promises';
import path from 'node:path';
import sharp from 'sharp';

const ROOT = path.resolve(import.meta.dirname, '..');
const SITE_CONTENT = await fs.readFile(path.join(ROOT, 'js/site-content.js'), 'utf8');
const SUPABASE_URL = SITE_CONTENT.match(/SUPABASE_URL = '([^']+)'/)?.[1];
const SUPABASE_ANON = process.env.SUPABASE_ANON_KEY || SITE_CONTENT.match(/SUPABASE_ANON = '([^']+)'/)?.[1];
const STORAGE_PREFIX = `${SUPABASE_URL}/storage/v1/object/public/images/`;
const OUTPUT_ROOT = path.join(ROOT, 'images/previews');
const MANIFEST_JS = path.join(ROOT, 'js/image-preview-manifest.js');
const REPORT_JSON = path.join(OUTPUT_ROOT, 'manifest.json');

if (!SUPABASE_URL || !SUPABASE_ANON) throw new Error('Supabase public configuration was not found.');

const sources = [
  ['gallery_photos', ['image_url']],
  ['home_showcase', ['image_url']],
  ['door_styles', ['image_url', 'banner_image']],
  ['flooring_products', ['image_url', 'corner_image_url']],
  ['flooring_images', ['image_url']],
  ['outdoor_products', ['image_url']],
  ['outdoor_images', ['image_url']],
];

const headers = { apikey: SUPABASE_ANON, Authorization: `Bearer ${SUPABASE_ANON}` };
const urls = new Set();
for (const [table, fields] of sources) {
  const response = await fetch(`${SUPABASE_URL}/rest/v1/${table}?select=${fields.join(',')}`, { headers });
  if (!response.ok) throw new Error(`${table} query failed: ${response.status}`);
  const rows = await response.json();
  for (const row of rows) {
    for (const field of fields) {
      const value = row[field];
      if (typeof value === 'string' && value.startsWith(STORAGE_PREFIX)) urls.add(value);
    }
  }
}

await fs.rm(OUTPUT_ROOT, { recursive: true, force: true });
await fs.mkdir(OUTPUT_ROOT, { recursive: true });

function previewRelativePath(url) {
  const objectPath = decodeURIComponent(new URL(url).pathname.split('/storage/v1/object/public/images/')[1] || '');
  const parsed = path.posix.parse(objectPath);
  return path.posix.join('images/previews', parsed.dir, `${parsed.name}.webp`);
}

async function build(url) {
  const response = await fetch(url, { headers: { 'cache-control': 'no-cache' } });
  if (!response.ok) throw new Error(`Image fetch failed (${response.status}): ${url}`);
  const original = Buffer.from(await response.arrayBuffer());
  const relative = previewRelativePath(url);
  const destination = path.join(ROOT, relative);
  await fs.mkdir(path.dirname(destination), { recursive: true });
  const preview = await sharp(original)
    .rotate()
    .resize({ width: 720, height: 720, fit: 'inside', withoutEnlargement: true })
    .webp({ quality: 76, effort: 5 })
    .toBuffer();
  await fs.writeFile(destination, preview);
  const originalMeta = await sharp(original).metadata();
  const previewMeta = await sharp(preview).metadata();
  return {
    originalUrl: url,
    previewPath: relative,
    originalBytes: original.length,
    previewBytes: preview.length,
    originalWidth: originalMeta.width,
    originalHeight: originalMeta.height,
    previewWidth: previewMeta.width,
    previewHeight: previewMeta.height,
  };
}

const pending = [...urls].sort();
const results = [];
const workers = Array.from({ length: Math.min(6, pending.length) }, async () => {
  while (pending.length) results.push(await build(pending.shift()));
});
await Promise.all(workers);
results.sort((a, b) => a.originalUrl.localeCompare(b.originalUrl));

const mapping = Object.fromEntries(results.map(item => [item.originalUrl, item.previewPath]));
const js = `// Generated by scripts/build-image-previews.mjs. Do not edit by hand.\nwindow.CENTRAL_HOME_IMAGE_PREVIEWS = ${JSON.stringify(mapping, null, 2)};\n`;
await fs.writeFile(MANIFEST_JS, js);

const totals = results.reduce((sum, item) => {
  sum.originalBytes += item.originalBytes;
  sum.previewBytes += item.previewBytes;
  return sum;
}, { originalBytes: 0, previewBytes: 0 });
await fs.writeFile(REPORT_JSON, JSON.stringify({ generatedAt: new Date().toISOString(), count: results.length, ...totals, images: results }, null, 2));

const saved = totals.originalBytes - totals.previewBytes;
console.log(JSON.stringify({
  count: results.length,
  originalBytes: totals.originalBytes,
  previewBytes: totals.previewBytes,
  savedBytes: saved,
  savedPercent: Number((saved / totals.originalBytes * 100).toFixed(2)),
}, null, 2));
